
// ============================================================
// 测试程序：验证大掩码取模优化
// 
// 测试场景：
//   1. 边界值 (mask=2047) 应该用 andi
//   2. 大掩码 (mask=4095, 8191, 16383, 32767, 65535) 应该用 li + and
//   3. 运行时取模应该用 rem
// ============================================================

// ===== 边界值 (2047，应该用 andi) =====
int mod_2048(int x) {
    return x % 2048;
}

// ===== 大掩码 (应该用 li + and) =====
int mod_4096(int x) {
    return x % 4096;
}

int mod_8192(int x) {
    return x % 8192;
}

int mod_16384(int x) {
    return x % 16384;
}

int mod_32768(int x) {
    return x % 32768;
}

int mod_65536(int x) {
    return x % 65536;
}

// ===== 运行时取模 (应该用 rem) =====
int mod_runtime(int a, int b) {
    return a % b;
}

int main() {
    int x = 50000;
    
    int a = mod_2048(x);      // 50000 % 2048 = 50000 - 2048*24 = 848
    int b = mod_4096(x);      // 50000 % 4096 = 50000 - 4096*12 = 848
    int c = mod_8192(x);      // 50000 % 8192 = 50000 - 8192*6 = 848
    int d = mod_16384(x);     // 50000 % 16384 = 50000 - 16384*3 = 848
    int e = mod_32768(x);     // 50000 % 32768 = 17232
    int f = mod_65536(x);     // 50000 % 65536 = 50000
    int g = mod_runtime(x, 7); // 50000 % 7 = 6
    
    return a + b + c + d + e + f + g;
}